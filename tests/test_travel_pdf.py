def test_generate_travel_typst_john_sample(tmp_path):
    usfm = write_sample_zip(tmp_path / "sample.zip")
    out = tmp_path / "john.typ"
    books = generate_travel_typst(usfm, out, books=("John",))
    text = out.read_text()
    assert books[0]["book"] == "John"
    assert text.count("#book-title") == 1
    assert "Genesis" not in text or "Genesis 1:1" in text
    assert "In the beginning." not in text
    assert "#set page(" in text
    assert "4.75in" in text or "4.75" in text


@pytest.mark.skipif(not USFM_ZIP.exists(), reason="official BSB USFM zip not present")
def test_real_usfm_john_preserves_corpus_text(tmp_path):
    out = tmp_path / "john.typ"
    books = generate_travel_typst(USFM_ZIP, out, books=("John",))
    assert [book["book"] for book in books] == ["John"]
    assert len(books[0]["chapters"]) == 21
    text = out.read_text(encoding="utf-8")
    assert "For God so loved the world" in text
    assert "In the beginning was the Word" in text
    assert "#woc[" in text
    assert text.count("#chapter-drop(") == 21
    assert "Source Serif 4" not in text
    assert "Lexend" not in text
